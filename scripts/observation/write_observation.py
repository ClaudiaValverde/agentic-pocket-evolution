#!/usr/bin/env python
"""Collect the observation-error outputs into results/numbers.json (key "observation", merged) and write the
number tables of results/observation/<snapshot>/OBSERVATION_numbers.md (every number in OBSERVATION.md comes
from here).

  python scripts/observation/write_observation.py --tierl data/tierL/<id>
"""
from __future__ import annotations

import argparse
import json
import os
import tempfile
from pathlib import Path

import pandas as pd

P = Path(__file__).resolve().parents[2]
SNAP = "20261030T085136Z"


def r3(x):
    return None if x is None else round(float(x), 4)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tierl", default=None)
    a = ap.parse_args()
    R = P / f"results/observation/{SNAP}"
    red = json.loads((R / "redetection.json").read_text())
    fa = json.loads((R / "false_a.json").read_text())
    rk = json.loads((R / "rescue_k.json").read_text()) if (R / "rescue_k.json").exists() else None
    tl = json.loads((P / a.tierl / "manifest.json").read_text()) if a.tierl else None
    tlv = json.loads((P / a.tierl / "verify_fp.json").read_text()) if a.tierl else None
    obs = {"snapshot_id": SNAP, "prereg_sha256": red["prereg_sha256"], "primary_tau": red["primary_tau"]}
    obs["redetection"] = {
        "n_sample": red["n_sample"], "n_seq_mismatch_skipped": red["n_seq_mismatch"],
        "method_hash_ok": red["method_hash_ok"],
        **{c: {"redetect": r3(h["redetect"]), "n_sites": h["n_sites"], "n_proteins": h["n_proteins"],
               "redetect_by_band": {b: r3(v) for b, v in h["redetect_by_band"].items()},
               "cos_matched_p05": r3(h["cos_matched"]["p05"]), "cos_matched_p10": r3(h["cos_matched"]["p10"]),
               "cos_matched_p50": r3(h["cos_matched"]["p50"])} for c, h in red["headline"].items()},
        "by_tau": [{k: (r3(v) if isinstance(v, float) else v) for k, v in s.items()} for s in red["summary"]],
    }
    obs["false_A"] = {"sources": fa["sources"], "n_known": fa["n_known"], "n_proteins": fa["n_proteins"],
                      "A_primary": fa["A_primary"], "A_sens": fa["A_sens"],
                      "by_ligand_class": fa["by_ligand_class"], "by_size_bin": fa.get("by_size_bin"),
                      "by_half": fa["by_half"], "by_band": fa["by_band"],
                      "by_overlap_threshold": fa.get("false_A_primary_by_overlap_threshold")}
    if rk:
        obs["rescue"] = {"k_prereg": rk["k"], "k_largest_meeting_target": rk["k_largest_meeting_target"],
                         "false_A_target": rk["false_A_target"], "tune": rk["tune_table"], "test": rk["test_table"],
                         "n_cases": rk["n_cases"], "n_controls": rk["n_controls"]}
    if tl:
        obs["tierL"] = {"id": tl["snapshot_id"], **tl["per_tier"]["L"], "run_wall_s": tl["run_wall_s"],
                        "structures_per_s": tl["run_structures_per_s"], "n_bad_method_hash": tl["n_bad_method_hash"],
                        "verify_fp_ok": tlv["ok"], "verify_fp_n": tlv["n_structures"], "verify_min_cos": tlv["min_cos"],
                        "tier3_overlap_accessions": tl["tier3_overlap_accessions"]}
    nj = P / "results/numbers.json"
    cur = json.loads(nj.read_text()) if nj.exists() else {}
    cur["observation"] = obs
    fd, tmp = tempfile.mkstemp(dir=nj.parent, prefix=".numbers.", suffix=".json")
    with os.fdopen(fd, "w") as fh:
        json.dump(cur, fh, indent=1, default=str)
    os.replace(tmp, nj)
    # number tables
    L = ["# OBSERVATION numbers (generated by scripts/observation/write_observation.py)", ""]
    L += ["## Re-detection (primary tau = %s)" % red["primary_tau"], "",
          "| comparison | proteins | v6 sites | re-detected | 70-90 | >=90 | cos p05 | cos p10 | cos p50 |", "|---|---|---|---|---|---|---|---|---|"]
    for c, h in obs["redetection"].items():
        if isinstance(h, dict) and "redetect" in h:
            b = h["redetect_by_band"]
            L.append(f"| {c} | {h['n_proteins']} | {h['n_sites']} | {h['redetect']} | {b.get('70-90')} | {b.get('>=90')} | "
                     f"{h['cos_matched_p05']} | {h['cos_matched_p10']} | {h['cos_matched_p50']} |")
    L += ["", "| comparison | tau | re-detect | reverse |", "|---|---|---|---|"]
    for s in obs["redetection"]["by_tau"]:
        L.append(f"| {s['comparison']} | {s['tau']} | {s['redetect']} | {s['reverse_redetect']} |")
    L += ["", "## False-A on known sites (A primary: region pLDDT >= 90, frac<70 <= 0.2; detected = atlas site covers >= 50 %)", "",
          "| stratum | value | known | A-eligible | false-A n | false-A rate |", "|---|---|---|---|---|---|"]
    for key in ("A_primary", "A_sens"):
        x = fa[key]
        L.append(f"| all ({key}) | - | {x['n_known']} | {x['n_A_eligible']} | {x['n_false_A']} | {r3(x['false_A'])} |")
    for st in ("by_ligand_class", "by_size_bin", "by_source", "by_half", "by_tier"):
        for k, x in (fa.get(st) or {}).items():
            L.append(f"| {st[3:]} | {k} | {x['n_known']} | {x['n_A_eligible']} | {x['n_false_A']} | {r3(x['false_A'])} |")
    L += ["", "false-A (primary) vs coverage threshold: " + json.dumps(fa.get("false_A_primary_by_overlap_threshold"))]
    s = pd.read_csv(R / "false_a_strata.csv")
    org = s[(s.criterion == "A_primary") & (s.stratum == "organism") & (s.n_A_eligible >= 30)]
    L += ["", "| organism (A-eligible >= 30) | A-eligible | false-A rate |", "|---|---|---|"]
    for r in org.sort_values("n_A_eligible", ascending=False).itertuples():
        L.append(f"| {r.value} | {r.n_A_eligible} | {r3(r.false_A)} |")
    if rk:
        L += ["", f"## Rescue (hit = {rk['hit_rule']}; target {rk['false_A_target']}; prereg k = {rk['k']}; "
                  f"largest k meeting target = {rk['k_largest_meeting_target']})", "",
              "| half | k | false-A before | cases still A | false-A after | controls rescued |", "|---|---|---|---|---|---|"]
        t = pd.read_csv(R / "rescue_k_table.csv")
        for r in t[(t.criterion == "A_primary")].itertuples():
            L.append(f"| {r.rule}/{r.half} | {r.k} | {r3(r.false_A_before)} | {r3(r.frac_cases_still_A)} | "
                     f"{r3(r.false_A_after)} | {r3(r.control_rescued_frac)} |")
    if tl:
        L += ["", "## Tier L", "", "```", json.dumps(obs["tierL"], indent=1), "```"]
    (R / "OBSERVATION_numbers.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
